private class ItemInput(description: String = "", quantity: String = "1", price: String = "") {
    var description by mutableStateOf(description)
    var quantity by mutableStateOf(quantity)
    var price by mutableStateOf(price)

    fun parse(): LineItem? {
        val q = parseQuantity(quantity) ?: return null
        val p = Money.parse(price) ?: return null
        if (description.isBlank()) return null
        return LineItem(description.trim(), q, p)
    }
}

private class TaxInput {
    var label by mutableStateOf("")
    var rate by mutableStateOf("")

    fun parse(): TaxRate? {
        val bp = parsePercentToBasisPoints(rate) ?: return null
        if (label.isBlank()) return null
        return TaxRate(label.trim(), bp)
    }
}

/**
 * Invoice / quotation builder. Every figure shown is computed by [DocumentCalculator];
 * nothing here is generated by AI.
 */
@Composable
fun DocBuilderScreen(vm: AppViewModel, kind: DocKind) {
    val invoice = kind == DocKind.INVOICE
    var number by rememberSaveable { mutableStateOf(vm.nextDocumentNumber(kind)) }
    var date by rememberSaveable { mutableStateOf(LocalDate.now().toString()) }
    var due by rememberSaveable { mutableStateOf("") }
    var customer by rememberSaveable { mutableStateOf("") }
    var phone by rememberSaveable { mutableStateOf("") }
    var discount by rememberSaveable { mutableStateOf("") }
    var payment by rememberSaveable { mutableStateOf("") }
    var notes by rememberSaveable { mutableStateOf("") }
    var showErrors by remember { mutableStateOf(false) }
    val items = remember { mutableStateListOf(ItemInput()) }
    val taxes = remember { mutableStateListOf<TaxInput>() }

    val parsedDate = parseDate(date)
    val parsedDue = if (due.isBlank()) null else parseDate(due)
    val parsedItems = items.map { it.parse() }
    val parsedTaxes = taxes.map { it.parse() }
    val parsedDiscount = if (discount.isBlank()) Money.ZERO else Money.parse(discount)
    val parsedPayment = if (payment.isBlank()) null else Money.parse(payment)
    val valid = parsedDate != null && customer.isNotBlank() && parsedItems.isNotEmpty() && parsedItems.all { it != null } &&
        parsedTaxes.all { it != null } && parsedDiscount != null && (payment.isBlank() || parsedPayment != null) &&
        (due.isBlank() || parsedDue != null)

    val totals = if (parsedItems.isNotEmpty() && parsedItems.all { it != null } && parsedDiscount != null && parsedTaxes.all { it != null }) {
        DocumentCalculator.calculate(
            parsedItems.filterNotNull(),
            if (parsedDiscount.isZero) Discount.None else Discount.Fixed(parsedDiscount),
            parsedTaxes.filterNotNull(),
            if (invoice && parsedPayment != null && parsedPayment.minor > 0) listOf(RecordedPayment(parsedPayment)) else emptyList(),
        )
    } else null

    Column(Modifier.fillMaxSize()) {
        ScreenTitle(t(if (invoice) Str.TASK_INVOICE else Str.TASK_QUOTATION), onBack = { vm.back() })
        ScrollColumn {
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                Field(t(Str.DOCUMENT_NUMBER), number, { number = it }, Modifier.weight(1f))
                Field(t(Str.DATE), date, { date = it }, Modifier.weight(1f), error = if (showErrors && parsedDate == null) t(Str.INVALID_DATE) else null)
            }
            Field(t(Str.FIELD_CUSTOMER_NAME), customer, { customer = it }, error = if (showErrors && customer.isBlank()) t(Str.REQUIRED_FIELD) else null)
            Field(t(Str.FIELD_CUSTOMER_PHONE), phone, { phone = it })
            Field(
                t(if (invoice) Str.DUE_DATE_OPTIONAL else Str.VALID_UNTIL_OPTIONAL), due, { due = it },
                error = if (due.isNotBlank() && parsedDue == null) t(Str.INVALID_DATE) else null,
            )

            SectionLabel(t(Str.DOC_ITEM))
            if (showErrors && items.isEmpty()) Text(t(Str.NEED_ONE_ITEM), color = MaterialTheme.colorScheme.error)
            items.forEachIndexed { index, item ->
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                        Field(t(Str.DESCRIPTION), item.description, { item.description = it }, error = if (showErrors && item.description.isBlank()) t(Str.REQUIRED_FIELD) else null)
                        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            Field(t(Str.QUANTITY), item.quantity, { item.quantity = it }, Modifier.weight(1f), numeric = true,
                                error = if (showErrors && parseQuantity(item.quantity) == null) t(Str.INVALID_QUANTITY) else null)
                            Field(t(Str.UNIT_AMOUNT), item.price, { item.price = it }, Modifier.weight(1f), numeric = true,
                                error = if (showErrors && Money.parse(item.price) == null) t(Str.INVALID_AMOUNT) else null)
                        }
                        parsedItems.getOrNull(index)?.let { Text("${t(Str.DOC_AMOUNT)}: ${it.lineTotal.format()}") }
                        if (items.size > 1) TextButton(onClick = { items.removeAt(index) }) { Text(t(Str.REMOVE)) }
                    }
                }
            }
            OutlinedButton(onClick = { items.add(ItemInput()) }) { Text(t(Str.ADD_ITEM)) }

            Field(t(Str.DISCOUNT_OPTIONAL), discount, { discount = it }, numeric = true, error = if (parsedDiscount == null) t(Str.INVALID_AMOUNT) else null)

            SectionLabel(t(Str.DOC_TOTAL))
            NoticeCard(t(Str.TAX_NOTICE))
            taxes.forEachIndexed { index, tax ->
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    Field(t(Str.TAX_LABEL), tax.label, { tax.label = it }, Modifier.weight(1f), error = if (showErrors && tax.label.isBlank()) t(Str.REQUIRED_FIELD) else null)
                    Field(t(Str.TAX_RATE), tax.rate, { tax.rate = it }, Modifier.weight(1f), numeric = true,
                        error = if (tax.rate.isNotBlank() && parsePercentToBasisPoints(tax.rate) == null || showErrors && tax.rate.isBlank()) t(Str.INVALID_AMOUNT) else null)
                }
                TextButton(onClick = { taxes.removeAt(index) }) { Text(t(Str.REMOVE)) }
            }
            OutlinedButton(onClick = { taxes.add(TaxInput()) }) { Text(t(Str.ADD_TAX)) }

            if (invoice) {
                SectionLabel(t(Str.RECORD_PAYMENT))
                NoticeCard(t(Str.PAYMENT_NOTICE), warning = true)
                Field(t(Str.DOC_PAID), payment, { payment = it }, numeric = true, error = if (payment.isNotBlank() && parsedPayment == null) t(Str.INVALID_AMOUNT) else null)
            }
            Field(t(Str.NOTES_OPTIONAL), notes, { notes = it }, multiline = true)

            totals?.let { tt ->
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(12.dp), verticalArrangement = Arrangement.spacedBy(4.dp)) {
                        Text("${t(Str.DOC_SUBTOTAL)}: ${tt.subtotal.format()}")
                        if (!tt.discount.isZero) Text("${t(Str.DOC_DISCOUNT)}: -${tt.discount.format()}")
                        tt.taxes.forEach { Text("${it.rate.label} (${formatBasisPoints(it.rate.basisPoints)}): ${it.amount.format()}") }
                        HorizontalDivider()
                        Text("${t(Str.DOC_TOTAL)}: ${tt.total.format()}", fontWeight = FontWeight.Bold)
                        if (invoice) {
                            Text("${t(Str.DOC_BALANCE)}: ${tt.balanceDue.format()}")
                            Text("${t(Str.DOC_STATUS)}: ${t(DocumentRenderer.statusLabel(tt.status))}")
                        }
                        Text(t(Str.SOURCE_CALCULATED), style = MaterialTheme.typography.bodySmall)
                    }
                }
            }

            Button(
                onClick = {
                    if (!valid) { showErrors = true; return@Button }
                    vm.openSalesDocument(
                        SalesDocument(
                            kind = kind, number = number.trim(), date = parsedDate!!, customerName = customer.trim(), customerPhone = phone.trim(),
                            items = parsedItems.filterNotNull(),
                            discount = if (parsedDiscount!!.isZero) Discount.None else Discount.Fixed(parsedDiscount),
                            taxes = parsedTaxes.filterNotNull(),
                            payments = if (invoice && parsedPayment != null && parsedPayment.minor > 0) listOf(RecordedPayment(parsedPayment)) else emptyList(),
                            dueOrValidUntil = parsedDue, notes = notes,
                        ),
                    )
                },
                modifier = Modifier.fillMaxWidth(),
            ) { Text(t(Str.PREVIEW)) }
        }
    }
}

private fun parseDate(s: String): LocalDate? = try { LocalDate.parse(s.trim()) } catch (e: DateTimeParseException) { null }
