#!/usr/bin/env python3
"""Generate Android strings.xml files from en.py / am.py / om.py and check them against the Kotlin sources.

Run from anywhere: python3 tools/i18n/gen.py  (exits non-zero if a key used in code is missing in English,
or a translation has different format placeholders than English).
"""
import importlib.util, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
APP = ROOT / "android/app/src/main"

def load(name):
    spec = importlib.util.spec_from_file_location(name, HERE / f"{name}.py")
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    return mod.S

def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if s[:1] in "@?":
        s = "\\" + s
    return s

PH = re.compile(r"%(\d+\$)?[-#+ 0,(]*\d*(\.\d+)?[sdfx%]")
def placeholders(s):
    return sorted(m.group(0) for m in PH.finditer(s) if m.group(0) != "%%")

def write(lang_dir, strings, header):
    out = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {header} -->", "<resources>"]
    for k in sorted(strings):
        attrs = ' translatable="false"' if k == "app_name" and lang_dir == "values" else ""
        out.append(f'    <string name="{k}"{attrs}>{esc(strings[k])}</string>')
    out.append("</resources>\n")
    path = APP / "res" / lang_dir / "strings.xml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    return path

def main():
    en, am, om = load("en"), load("am"), load("om")
    used = set(re.findall(r"R\.string\.([A-Za-z0-9_]+)", "\n".join(p.read_text() for p in (APP / "kotlin").rglob("*.kt"))))
    manifest = set(re.findall(r"@string/([A-Za-z0-9_]+)", (APP / "AndroidManifest.xml").read_text()))
    problems = []
    for k in sorted((used | manifest) - set(en)):
        problems.append(f"missing English string: {k}")
    for k in sorted(set(en) - used - manifest):
        problems.append(f"unused English string: {k}")
    for name, tr in (("am", am), ("om", om)):
        for k, v in tr.items():
            if k not in en:
                problems.append(f"{name}: unknown key {k}")
            elif placeholders(v) != placeholders(en[k]):
                problems.append(f"{name}: placeholder mismatch in {k}")
    missing_am = sorted(set(en) - set(am))
    if missing_am:
        problems.append("am: missing " + ", ".join(missing_am))
    write("values", en, "Generated by tools/i18n/gen.py from en.py. Edit the .py file, not this one.")
    write("values-am", {k: v for k, v in am.items() if k != "app_name"}, "Generated by tools/i18n/gen.py from am.py.")
    write("values-om", om, "Generated by tools/i18n/gen.py from om.py. Partial translation: missing keys fall back to English.")
    print(f"en={len(en)} am={len(am)} om={len(om)} used={len(used | manifest)}")
    for p in problems:
        print(p)
    return 1 if problems else 0

if __name__ == "__main__":
    sys.exit(main())
